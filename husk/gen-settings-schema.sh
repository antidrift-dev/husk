#!/bin/zsh
# Regenerate macos/Sources/Husk/HuskConfigSchema+Data.swift: every Ghostty config option husk's
# Settings window can edit (All Settings tab), from Ghostty's own Config.zig. Run after merging a new
# Ghostty version, after a debug build (it reads defaults from that build's `+show-config --default`).
#
#   husk/gen-settings-schema.sh [path/to/husk.app]
set -e
setopt pipefail
ROOT=${0:A:h:h}
cd "$ROOT"
APP=${1:-$ROOT/macos/build.noindex/Debug/husk.app}
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT

PATH="$ROOT/.toolchain/zig-aarch64-macos-0.17.0:$PATH" \
  zig build -Demit-macos-app=false -Demit-webdata=true -Demit-docs=false --prefix "$OUT"
"$APP/Contents/MacOS/ghostty" +show-config --default --no-pager > "$OUT/defaults.txt"

python3 -I - "$OUT/share/ghostty/webdata/husk-config-schema.json" "$OUT/defaults.txt" \
  macos/Sources/Husk/HuskConfigSchema+Data.swift <<'EOF'
import json, re, sys
schema_path, defaults_path, out_path = sys.argv[1:]
options = json.load(open(schema_path))

defaults = {}
for line in open(defaults_path):
    if " = " in line or line.rstrip().endswith(" ="):
        name, _, value = line.rstrip("\n").partition(" =")
        defaults.setdefault(name, []).append(value[1:] if value.startswith(" ") else value)

# Not on macOS, command-line only, or not safe to set from Settings.
SKIP_PREFIX = ("gtk-", "x11-", "linux-", "adw-", "freetype-", "wayland-")
SKIP = {"language", "window-subtitle", "window-show-tab-bar", "quit-after-last-window-closed-delay",
        "async-backend", "class", "config-file", "config-default-files", "input", "bell-audio-path",
        "bell-audio-volume"}
# Types that take one entry per line (each a separate `name = value`).
LIST_TYPES = ("Repeatable", "Keybinds", "Palette", "RemapSet", "ColorList")
COLOR_TYPES = ("TerminalColor", "BoldColor")

CATEGORIES = [
    ("Font", r"^(font-|adjust-|grapheme-width)"),
    ("Colors", r"^(background|foreground|palette|minimum-contrast|alpha-blending|bold-color|faint-opacity"
               r"|selection-(foreground|background)|search-|cursor-(color|text|opacity)|split-divider-color"
               r"|unfocused-split|window-padding-color|window-colorspace|theme)"),
    ("Cursor", r"^cursor-"),
    ("Mouse", r"^(mouse-|click-|right-click|middle-click|focus-follows-mouse)"),
    ("Clipboard & Selection", r"^(clipboard-|copy-on-select|selection-|link)"),
    ("Keyboard", r"^(keybind|key-remap|macos-option-as-alt|macos-auto-secure-input|macos-secure-input)"),
    ("Windows & Tabs", r"^(window-|maximize|fullscreen|resize-overlay|split-|tab-|initial-window|title|macos-window"
                       r"|macos-titlebar|macos-non-native|confirm-close|quit-after|undo-timeout|scrollbar)"),
    ("Quick Terminal", r"^quick-terminal"),
    ("Shell & Commands", r"^(shell-integration|command|initial-command|working-directory|env|term$|wait-after"
                         r"|abnormal-command|enquiry|scrollback|scroll-to-bottom)"),
    ("Notifications", r"^(notify-|bell-|desktop-notifications|app-notifications|progress-style)"),
    ("macOS", r"^macos-"),
]

out, prev_doc = [], ""
for o in options:
    name, doc = o["name"], o["doc"] or prev_doc
    prev_doc = doc  # undocumented options share the doc above them
    if name.startswith(SKIP_PREFIX) or name in SKIP:
        continue
    short = o["type"].split(".")[-1]
    kind = o["kind"]
    if short.startswith(LIST_TYPES):
        kind = "list"
    elif short in COLOR_TYPES:
        kind = "color"
    category = next((c for c, rx in CATEGORIES if re.search(rx, name)), "Other")
    entry = {"name": name, "kind": kind, "category": category, "doc": doc.strip(),
             "default": defaults.get(name, [])}
    if "values" in o:
        entry["values"] = o["values"]
    if o.get("optional"):
        entry["optional"] = True
    out.append(entry)

blob = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
hashes = "#"
while ('"' + hashes) in blob:
    hashes += "#"
open(out_path, "w").write(
    "// Generated by husk/gen-settings-schema.sh from Ghostty's Config.zig. Don't edit by hand.\n"
    "// swiftlint:disable all\n\n"
    "extension HuskConfigSchema {\n"
    f"    static let json = {hashes}\"{blob}\"{hashes}\n"
    "}\n")
print(f"{len(out)} options → {out_path}")
EOF
